import { z } from "zod";

import {
  AGE_CATEGORIES,
  GENDERS,
  MEMBERSHIP_DURATIONS,
} from "@/lib/types";

/** Trims, collapses internal whitespace and normalises unicode spaces. */
export const normalizeName = (value: string): string =>
  value.replace(/\s+/g, " ").trim();

const nameSchema = z
  .string()
  .min(2, "Please enter your full name.")
  .max(200, "That name is too long.")
  .transform(normalizeName)
  .refine((value) => value.length >= 2, "Please enter your full name.");

const phoneSchema = z
  .string()
  .trim()
  .min(1, "Please enter a phone number.")
  .max(30, "That phone number is too long.")
  .refine(
    (value) => value.replace(/\D/g, "").length >= 7,
    "Please enter a valid phone number."
  )
  .refine(
    (value) => value.replace(/\D/g, "").length <= 15,
    "Please enter a valid phone number."
  );

const emailSchema = z
  .string()
  .trim()
  .max(200, "That email address is too long.")
  .refine(
    (value) => value === "" || /^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/.test(value),
    "Please enter a valid email address."
  );

/**
 * The registration schema.
 *
 * Optional fields use `""` (an empty string) rather than `null` and
 * `undefined` so that the schema's input and output types are identical.
 * This keeps React Hook Form's resolver typing simple and means the values
 * round-trip cleanly through the form controls. Normalisation to `null`
 * happens in the server action.
 */
/**
 * The base registration fields, shared by the public form and the
 * administrator form.
 *
 * Kept as a separate object schema so that `.omit()` can be applied to it
 * (Zod does not allow `omit` on a schema that carries a refinement).
 */
const registrationFields = {
  titleId: z.string().trim().min(1, "Please select a title."),
  fullName: nameSchema,
  gender: z.enum(GENDERS, { message: "Please select your gender." }),
  ageCategory: z.enum(AGE_CATEGORIES, { message: "Please select an age category." }),
  birthDay: z
    .number({ message: "Please select a day." })
    .int()
    .min(1, "Please select a day.")
    .max(31, "Please select a day.")
    .optional(),
  birthMonth: z
    .number({ message: "Please select a month." })
    .int()
    .min(1, "Please select a month.")
    .max(12, "Please select a month.")
    .optional(),
  serviceUnitIds: z.array(z.string().uuid()).optional(),
  primaryPhone: phoneSchema,
  whatsappSameAsPrimary: z.boolean(),
  whatsappPhone: z.union([z.literal(""), phoneSchema]),
  additionalPhones: z.array(phoneSchema).max(5, "You may add up to 5 extra numbers.").optional(),
  email: emailSchema,
  residentialAddress: z
    .string()
    .trim()
    .max(500, "That address is too long."),
  membershipDuration: z.enum(MEMBERSHIP_DURATIONS, {
    message: "Please select how long you have been a member.",
  }),
  suggestions: z
    .string()
    .trim()
    .max(2000, "Please keep this under 2000 characters."),
  photo: z
    .object({
      publicId: z.string().min(1, "Please upload your photograph."),
      format: z.string().min(1),
      width: z.number().int().positive(),
      height: z.number().int().positive(),
      bytes: z.number().int().positive(),
    })
    .nullable(),
  consentAccepted: z.boolean().refine((value) => value === true, {
    message: "Please confirm that you have read and accept the privacy notice.",
  }),
  isChildRegistration: z.boolean(),
  guardianName: z.string().trim().max(200),
  guardianRelationship: z.string().trim().max(80),
  guardianPhone: z.union([z.literal(""), phoneSchema]),
  customValues: z.record(z.string(), z.unknown()).optional(),
  /** Idempotency key generated by the browser for this submission attempt. */
  submissionId: z.string().min(8).max(100),
};

/**
 * Cross-field validation shared by both forms.
 *
 * Day/month-only date of birth: both must be present or both absent.
 * February allows the 29th so that a leap-day birth date can be recorded.
 */
function validateRegistrationFields(
  data: {
    birthDay?: number;
    birthMonth?: number;
    isChildRegistration: boolean;
    guardianName: string;
    guardianPhone: string;
  },
  ctx: z.RefinementCtx
): void {
  const hasDay = data.birthDay !== undefined && data.birthDay !== null;
  const hasMonth = data.birthMonth !== undefined && data.birthMonth !== null;

  if (hasDay !== hasMonth) {
    ctx.addIssue({
      code: z.ZodIssueCode.custom,
      path: ["birthDay"],
      message: "Please select both a day and a month, or leave both empty.",
    });
  }

  if (hasDay && hasMonth) {
    const daysInMonth = new Date(2000, data.birthMonth as number, 0).getDate();
    const maxDay = data.birthMonth === 2 ? 29 : daysInMonth;
    if ((data.birthDay as number) > maxDay) {
      ctx.addIssue({
        code: z.ZodIssueCode.custom,
        path: ["birthDay"],
        message:
          data.birthMonth === 2
            ? "February only has 29 days."
            : "That day does not exist in the selected month.",
      });
    }
  }

  if (data.isChildRegistration) {
    if (!data.guardianName) {
      ctx.addIssue({
        code: z.ZodIssueCode.custom,
        path: ["guardianName"],
        message: "Please enter the name of the parent or guardian.",
      });
    }
    if (!data.guardianPhone) {
      ctx.addIssue({
        code: z.ZodIssueCode.custom,
        path: ["guardianPhone"],
        message: "Please enter a parent or guardian phone number.",
      });
    }
  }
}

export const registrationSchema = z
  .object(registrationFields)
  .superRefine(validateRegistrationFields);

export type RegistrationFormValues = z.infer<typeof registrationSchema>;

/**
 * Administrator member-creation schema.
 *
 * The administrator form shares the registration validation but does not
 * require the public privacy consent, because the administrator is acting
 * on the church's behalf. The consent record is still written, with the
 * notice version applied at the time of creation.
 */
export const adminMemberSchema = z
  .object(
    registrationFields as Omit<
      typeof registrationFields,
      "consentAccepted" | "submissionId"
    >
  )
  .superRefine(validateRegistrationFields);

export type AdminMemberFormValues = z.infer<typeof adminMemberSchema>;
